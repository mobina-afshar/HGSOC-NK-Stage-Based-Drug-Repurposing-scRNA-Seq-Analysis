write.csv(
  
  as.matrix(pb_counts),
  
  out_dir(
    "pseudobulk",
    "05_pseudobulk_counts.csv"
  )
)


# Export pseudobulk metadata.

write.csv(
  
  pb_meta,
  
  out_dir(
    "pseudobulk",
    "06_pseudobulk_metadata.csv"
  ),
  
  row.names = TRUE
)


