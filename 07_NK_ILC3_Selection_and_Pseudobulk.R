
############################################################
# GSE184880 - HGSOC scRNA-seq Analysis
# Script 07: NK/ILC3 Selection and Pseudobulk Aggregation
#
# Workflow:
# Select cluster 0 (NK-like) and cluster 11 (ILC3),
# then aggregate raw RNA counts at the patient level.
#
# Purpose:
# - Define the two populations used in stage-associated analysis.
# - Assign Workflow 2 population labels.
# - Aggregate raw counts by patient and population.
# - Generate pseudobulk metadata and QC summaries.
#
# Input:
# - config.yaml
# - results/rds/07_HGSOC_TNK_ILC_Final_Annotated.rds
#
# Output:
# - Selected NK-like and ILC3 cell object
# - Patient-population cell counts
# - Patient-by-stage design summary
# - Pseudobulk QC summary
# - Pseudobulk count matrix and metadata
# - results/rds/08_NK_ILC3_StageAnalysis_Object.rds
# - results/rds/09_pseudobulk_counts.rds
# - results/rds/10_pseudobulk_metadata.rds
# - logs/07_pseudobulk_sessionInfo.txt
#
# IMPORTANT:
# - Cluster 0 is operationally defined as NK-like.
# - Cluster 11 is defined as ILC3.
# - Raw RNA counts are aggregated by patient and population.
# - All patient-population pairs with at least one cell are retained.
# - No minimum-cell threshold is applied.
# - Early is the reference group for downstream stage analysis.
############################################################


############################################################
# 1. Load Project Configuration
############################################################

# Ensure that the script is launched from the repository root.

if (!file.exists("config.yaml")) {
  
  stop(
    "config.yaml was not found. ",
    "Run this script from the project root."
  )
}


# Check and load the YAML package.

if (!requireNamespace("yaml", quietly = TRUE)) {
  
  stop(
    "Package 'yaml' is required. ",
    "Install it using install.packages('yaml')."
  )
}


# Read project configuration.

cfg <- yaml::read_yaml("config.yaml")


# Define project directories.

PROJECT_ROOT <- normalizePath(
  getwd(),
  winslash = "/",
  mustWork = TRUE
)

RESULTS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$results
)

LOGS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$logs
)

RAW_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$raw_data
)

RDS_DIR <- file.path(
  RESULTS_DIR,
  "rds"
)


# Create required output directories.

dir.create(
  RESULTS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  LOGS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  RDS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)


# Set project-wide random seed.

set.seed(cfg$project$seed)


############################################################
# 2. Define Shared Helper Functions
############################################################

# Generate output file paths and create parent directories.

out_dir <- function(...) {
  
  path <- file.path(
    RESULTS_DIR,
    ...
  )
  
  dir.create(
    dirname(path),
    recursive = TRUE,
    showWarnings = FALSE
  )
  
  return(path)
}


# Check whether required R packages are installed.

require_pkgs <- function(pkgs) {
  
  missing <- pkgs[
    !vapply(
      pkgs,
      requireNamespace,
      logical(1),
      quietly = TRUE
    )
  ]
  
  if (length(missing) > 0) {
    
    stop(
      "Install missing packages before continuing: ",
      paste(missing, collapse = ", ")
    )
  }
}


# Save R session information for reproducibility.

save_session <- function(tag) {
  
  capture.output(
    sessionInfo(),
    file = file.path(
      LOGS_DIR,
      paste0(tag, "_sessionInfo.txt")
    )
  )
}


############################################################
# 3. Load Required Packages
############################################################

require_pkgs(
  c(
    "Seurat",
    "Matrix",
    "dplyr"
  )
)

library(Seurat)
library(Matrix)
library(dplyr)


############################################################
# 4. Load Final Annotated T/NK/ILC Object
############################################################

# Load the retained T/NK/ILC object generated by Script 06.

input_rds <- out_dir(
  "rds",
  "07_HGSOC_TNK_ILC_Final_Annotated.rds"
)

if (!file.exists(input_rds)) {
  
  stop(
    "Run Script 06 first. Missing input file: ",
    input_rds
  )
}


obj <- readRDS(input_rds)


############################################################
# 5. Define Workflow 2 Populations
############################################################

# Explicitly assign the two populations used in the
# stage-associated analysis:
#
# Cluster 0  -> NK-like
# Cluster 11 -> ILC3
#
# These labels reproduce the established Workflow 2
# population definitions.

obj$Workflow2_Population <- NA_character_


# Assign NK-like label to cluster 0.

obj$Workflow2_Population[
  as.character(obj$seurat_clusters) == "0"
] <- "NK-like"


# Assign ILC3 label to cluster 11.

obj$Workflow2_Population[
  as.character(obj$seurat_clusters) == "11"
] <- "ILC3"


# Identify cells belonging to either selected population.

selected <- colnames(obj)[
  !is.na(obj$Workflow2_Population)
]


# Stop if no cells were selected.

if (length(selected) == 0) {
  
  stop(
    "No cells found in clusters 0 and 11."
  )
}


# Create the selected NK-like and ILC3 subset.

sub <- subset(
  obj,
  cells = selected
)


# Set the final population labels.

sub$Final_Annotation <- sub$Workflow2_Population


############################################################
# 6. Summarize Selected Cells by Patient and Population
############################################################

# Calculate the number of selected cells in each
# patient-population combination.

selected_cell_summary <- as.data.frame(
  table(
    sub$sample,
    sub$Final_Annotation
  )
)


# Export selected-cell counts.

write.csv(
  
  selected_cell_summary,
  
  out_dir(
    "pseudobulk",
    "01_selected_cells_by_sample_population.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 7. Save Selected NK-like and ILC3 Object
############################################################

# Save the selected cells before pseudobulk aggregation.

saveRDS(
  
  sub,
  
  out_dir(
    "rds",
    "08_NK_ILC3_StageAnalysis_Object.rds"
  )
)


############################################################
# 8. Extract Raw RNA Counts
############################################################

# Set the RNA assay as the default assay.

DefaultAssay(sub) <- "RNA"


# Join Seurat v5 RNA layers before extracting raw counts.
#
# This ensures that counts are available as a unified matrix.

if (inherits(sub[["RNA"]], "Assay5")) {
  
  sub <- JoinLayers(
    sub,
    assay = "RNA"
  )
}


# Extract raw RNA counts.
#
# IMPORTANT:
# Raw counts are used for pseudobulk aggregation,
# not normalized expression values.

counts <- GetAssayData(
  
  sub,
  
  assay = "RNA",
  
  layer = "counts"
)


############################################################
# 9. Prepare Cell-Level Metadata
############################################################

# Extract metadata in the same order as the count matrix.

meta <- sub@meta.data[
  colnames(counts),
  ,
  drop = FALSE
]


# Verify cell order consistency.

stopifnot(
  identical(
    rownames(meta),
    colnames(counts)
  )
)


# Convert sample identifiers and population labels to character.

meta$sample <- as.character(
  meta$sample
)

meta$Population <- as.character(
  meta$Workflow2_Population
)


# Define a unique pseudobulk identifier for each
# patient-population combination.

meta$pseudobulk_id <- paste(
  
  meta$Population,
  
  meta$sample,
  
  sep = "__"
)


############################################################
# 10. Verify Patient-Level Stage Information
############################################################

# Extract unique patient-stage combinations.

stage_map <- unique(
  meta[
    ,
    c(
      "sample",
      "stage_group"
    )
  ]
)


# Each patient must correspond to only one clinical stage.

if (anyDuplicated(stage_map$sample)) {
  
  stop(
    "A patient maps to more than one stage group."
  )
}


# Check for missing stage information.

if (anyNA(stage_map$stage_group)) {
  
  stop(
    "Missing stage_group in patient metadata."
  )
}


############################################################
# 11. Evaluate Patient-Population Eligibility
############################################################

# Count cells in each patient-population combination.
#
# All combinations containing at least one cell are retained.
# No minimum-cell threshold is applied.

cell_counts <- as.data.frame(
  table(
    meta$Population,
    meta$sample
  )
)


# Rename summary columns.

names(cell_counts) <- c(
  "Population",
  "sample",
  "n_cells"
)


# Mark patient-population combinations containing
# at least one cell as eligible.

cell_counts$eligible <- (
  cell_counts$n_cells > 0
)


# Export patient-population cell counts.

write.csv(
  
  cell_counts,
  
  out_dir(
    "pseudobulk",
    "02_patient_population_cell_counts.csv"
  ),
  
  row.names = FALSE
)


# Retain all eligible patient-population combinations.

eligible_pairs <- cell_counts[
  cell_counts$eligible,
  c(
    "Population",
    "sample"
  )
]


# Generate the corresponding pseudobulk identifiers.

pb_ids <- unique(
  meta$pseudobulk_id[
    meta$pseudobulk_id %in%
      paste(
        eligible_pairs$Population,
        eligible_pairs$sample,
        sep = "__"
      )
  ]
)


# Stop if no eligible combinations are available.

if (length(pb_ids) == 0) {
  
  stop(
    "No patient-population pairs available for pseudobulk aggregation."
  )
}


############################################################
# 12. Aggregate Raw Counts at the Patient Level
############################################################

# Initialize a sparse pseudobulk count matrix.
#
# Rows represent genes.
# Columns represent patient-population combinations.

pb_counts <- Matrix(
  
  0,
  
  nrow = nrow(counts),
  
  ncol = length(pb_ids),
  
  sparse = TRUE,
  
  dimnames = list(
    rownames(counts),
    pb_ids
  )
)


# Aggregate raw counts separately for each pseudobulk group.

for (id in pb_ids) {
  
  # Identify cells belonging to the current
  # patient-population combination.
  
  cells <- rownames(meta)[
    meta$pseudobulk_id == id
  ]
  
  
  # Sum raw counts across cells for each gene.
  
  pb_counts[, id] <- Matrix::rowSums(
    counts[
      ,
      cells,
      drop = FALSE
    ]
  )
}


############################################################
# 13. Generate Pseudobulk Metadata
############################################################

# Create one metadata record for each pseudobulk sample.

pb_meta <- data.frame(
  
  pseudobulk_id = pb_ids,
  
  Population = base::sub(
    "__.*",
    "",
    pb_ids
  ),
  
  sample = base::sub(
    ".*__",
    "",
    pb_ids
  ),
  
  stringsAsFactors = FALSE
)


# Assign the corresponding clinical stage to each patient.

pb_meta$stage_group <- stage_map$stage_group[
  match(
    pb_meta$sample,
    stage_map$sample
  )
]


# Define Early as the reference level.

pb_meta$stage_group <- factor(
  
  pb_meta$stage_group,
  
  levels = c(
    "Early",
    "Late"
  )
)


# Set pseudobulk identifiers as metadata row names.

rownames(pb_meta) <- pb_meta$pseudobulk_id


# Reorder metadata to match pseudobulk count matrix columns.

pb_meta <- pb_meta[
  colnames(pb_counts),
  ,
  drop = FALSE
]


# Verify count matrix and metadata consistency.

stopifnot(
  identical(
    rownames(pb_meta),
    colnames(pb_counts)
  )
)


# Check for unmatched patient-stage metadata.

if (anyNA(pb_meta$stage_group)) {
  
  stop(
    "Unmatched patient stage metadata."
  )
}


############################################################
# 14. Summarize Population-by-Stage Design
############################################################

# Generate a table showing the number of pseudobulk samples
# available for each population and clinical stage.

design_check <- as.data.frame.matrix(
  table(
    pb_meta$Population,
    pb_meta$stage_group
  )
)


# Export the population-by-stage design summary.

write.csv(
  
  design_check,
  
  out_dir(
    "pseudobulk",
    "03_population_by_stage_design.csv"
  )
)


############################################################
# 15. Perform Pseudobulk Quality Control
############################################################

# Calculate total counts and detected genes for each
# patient-population pseudobulk profile.

pb_qc <- data.frame(
  
  pseudobulk_id = colnames(pb_counts),
  
  total_counts = Matrix::colSums(pb_counts),
  
  detected_genes = Matrix::colSums(
    pb_counts > 0
  )
)


# Add population information.

pb_qc$Population <- pb_meta$Population[
  match(
    pb_qc$pseudobulk_id,
    rownames(pb_meta)
  )
]


# Add patient identifiers.

pb_qc$sample <- pb_meta$sample[
  match(
    pb_qc$pseudobulk_id,
    rownames(pb_meta)
  )
]


# Add clinical stage information.

pb_qc$stage_group <- pb_meta$stage_group[
  match(
    pb_qc$pseudobulk_id,
    rownames(pb_meta)
  )
]


# Export pseudobulk QC summary.

write.csv(
  
  pb_qc,
  
  out_dir(
    "pseudobulk",
    "04_pseudobulk_qc.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 16. Save Pseudobulk Count Matrix and Metadata
############################################################

# Save the sparse pseudobulk count matrix.

saveRDS(
  
  pb_counts,
  
  out_dir(
    "rds",
    "09_pseudobulk_counts.rds"
  )
)


# Save pseudobulk sample metadata.

saveRDS(
  
  pb_meta,
  
  out_dir(
    "rds",
    "10_pseudobulk_metadata.rds"
  )
)


