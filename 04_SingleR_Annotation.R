
############################################################
# GSE184880 - HGSOC scRNA-seq Analysis
# Script 04: SingleR Cell Annotation
#
# Purpose:
# Annotate cells from the globally clustered HGSOC dataset
# using the Human Primary Cell Atlas reference and SingleR.
# Identify broad immune-cell populations for downstream
# T/NK/ILC-focused analysis.
#
# Input:
# - config.yaml
# - results/rds/03_HGSOC_global_clustered.rds
# - Human Primary Cell Atlas reference (celldex)
#
# Output:
# - Cell-level SingleR annotations
# - Cluster-level annotation composition
# - SingleR UMAP visualization
# - Broad immune-cell subset
# - results/rds/04_HGSOC_immune_SingleR.rds
# - logs/04_singleR_annotation_sessionInfo.txt
#
# IMPORTANT:
# - Human Primary Cell Atlas is used as the reference.
# - SingleR annotation uses ref$label.main.
# - The broad immune-cell subset is selected using the
#   original label-based pattern.
# - SingleR labels are computational predictions and should
#   be interpreted together with marker-gene expression.
############################################################


############################################################
# 1. Load Project Configuration
############################################################

# Ensure that the script is launched from the repository root.

if (!file.exists("config.yaml")) {
  stop(
    "config.yaml was not found. ",
    "Run this script from the project root."
  )
}

# Check and load the YAML package.

if (!requireNamespace("yaml", quietly = TRUE)) {
  stop(
    "Package 'yaml' is required. ",
    "Install it using install.packages('yaml')."
  )
}

