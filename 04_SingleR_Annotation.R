  PROJECT_ROOT,
  cfg$paths$results
)

LOGS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$logs
)

RAW_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$raw_data
)

RDS_DIR <- file.path(
  RESULTS_DIR,
  "rds"
)

# Create required output directories.

dir.create(
  RESULTS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  LOGS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  RDS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

# Set project-wide random seed.

set.seed(cfg$project$seed)


############################################################
# 2. Define Shared Helper Functions
############################################################

# Generate output file paths and create parent directories.

out_dir <- function(...) {
  
  path <- file.path(
    RESULTS_DIR,
    ...
  )
  
  dir.create(
    dirname(path),
    recursive = TRUE,
    showWarnings = FALSE
  )
  
  return(path)
}


# Check whether required R packages are installed.

require_pkgs <- function(pkgs) {
  
  missing <- pkgs[
    !vapply(
      pkgs,
      requireNamespace,
      logical(1),
      quietly = TRUE
    )
  ]
  
  if (length(missing) > 0) {
    
    stop(
      "Install missing packages before continuing: ",
      paste(missing, collapse = ", ")
    )
  }
}


# Save R session information for reproducibility.

save_session <- function(tag) {
  
  capture.output(
    sessionInfo(),
    file = file.path(
      LOGS_DIR,
      paste0(tag, "_sessionInfo.txt")
    )
  )
}


############################################################
# 3. Load Required Packages
############################################################

require_pkgs(
  c(
    "Seurat",
    "SingleR",
    "celldex",
    "SummarizedExperiment",
    "SingleCellExperiment",
    "ggplot2",
    "dplyr"
  )
)

library(Seurat)
library(SingleR)
library(celldex)
library(SingleCellExperiment)
library(ggplot2)
library(dplyr)


############################################################
# 4. Load Global Clustered Seurat Object
############################################################

# Load the globally processed Seurat object generated by Script 03.

input_rds <- out_dir(
  "rds",
  "03_HGSOC_global_clustered.rds"
)

if (!file.exists(input_rds)) {
  
  stop(
    "Run Script 03 first. Missing input file: ",
    input_rds
  )
}

obj <- readRDS(input_rds)


# Set the RNA assay as the default assay.

DefaultAssay(obj) <- "RNA"


############################################################
# 5. Load Human Primary Cell Atlas Reference
############################################################

# Retrieve the Human Primary Cell Atlas reference dataset
# using the celldex package.

ref <- celldex::HumanPrimaryCellAtlasData()


# Check the availability of reference annotation labels.

if (is.null(ref$label.main)) {
  
  stop(
    "The Human Primary Cell Atlas reference ",
    "does not contain the expected label.main field."
  )
}


############################################################
# 6. Prepare Expression Data for SingleR
############################################################

# Inspect RNA assay layers before preparing the query matrix.

rna_layers <- Layers(
  obj[["RNA"]]
)

message(
  "RNA assay layers before joining: ",
  paste(rna_layers, collapse = ", ")
)


# Join RNA assay layers to ensure that normalized expression
# data are accessible as a unified matrix.

obj <- JoinLayers(
  obj,
  assay = "RNA"
)


# Extract normalized RNA expression data.
# The data layer contains LogNormalize-transformed expression.

query <- GetAssayData(
  
  obj,
  
  assay = "RNA",
  
  layer = "data"
)


# Identify genes shared between the query and reference datasets.

common_genes <- intersect(
  
  rownames(query),
  
  rownames(ref)
)


# Check the number of shared genes.

message(
  "Number of shared genes between query and reference: ",
  length(common_genes)
)

if (length(common_genes) < 1000) {
  
  warning(
    "Fewer than 1,000 shared genes were detected ",
    "between the query and reference datasets."
  )
}


# Stop if no sufficient gene overlap is available.

if (length(common_genes) == 0) {
  
  stop(
    "No shared genes were found between the query ",
    "and Human Primary Cell Atlas reference."
  )
}


############################################################
# 7. Perform SingleR Cell Annotation
############################################################

# Annotate individual cells using the Human Primary Cell Atlas.
#
# Reference labels:
# Main cell-type annotations (label.main)
#
# SingleR compares the query expression profiles with
# reference cell-type profiles and predicts a label for
# each query cell.

pred <- SingleR(
  
  test = query[
    common_genes,
    ,
    drop = FALSE
  ],
  
  ref = ref[
    common_genes,
    ,
    drop = FALSE
  ],
  
  labels = ref$label.main
)


# Add predicted and pruned labels to Seurat metadata.

obj$SingleR_label <- pred$labels

obj$SingleR_pruned <- pred$pruned.labels


############################################################
# 8. Summarize Cell-Level SingleR Annotations
############################################################

# Calculate the number of cells assigned to each predicted
# SingleR cell-type label.

singleR_cell_summary <- as.data.frame(
  table(obj$SingleR_label)
)

colnames(singleR_cell_summary) <- c(
  "SingleR_label",
  "Cells"
)


# Save cell-level annotation summary.

write.csv(
  
  singleR_cell_summary,
  
  out_dir(
    "annotation",
    "01_singleR_cell_labels.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 9. Summarize SingleR Annotation by Global Cluster
############################################################

# Evaluate the distribution of predicted cell types
# across the global Seurat clusters.

cluster_annotation <- as.data.frame(obj@meta.data) |>
  
  dplyr::count(
    seurat_clusters,
    SingleR_label,
    name = "cells"
  ) |>
  
  dplyr::group_by(
    seurat_clusters
  ) |>
  
  dplyr::mutate(
    
    percent = round(
      cells / sum(cells) * 100,
      2
    )
  ) |>
  
  dplyr::ungroup()


# Save cluster-level annotation composition.

write.csv(
  
  cluster_annotation,
  
  out_dir(
    "annotation",
    "02_singleR_cluster_composition.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 10. Visualize SingleR Cell Annotations
############################################################

# Generate a UMAP visualization colored by SingleR
# predicted cell-type labels.

p_singleR <- DimPlot(
  
  obj,
  
  reduction = "umap",
  
  group.by = "SingleR_label",
  
  label = FALSE,
  
  repel = TRUE
) +
  
  theme_classic()


# Save SingleR annotation UMAP.

ggsave(
  
  out_dir(
    "annotation",
    "03_singleR_umap.png"
  ),
  
  p_singleR,
  
  width = 12,
  
  height = 8,
  
  dpi = 300
)


############################################################
# 11. Identify Broad Immune-Cell Populations
############################################################

# Define the original broad immune-cell label pattern.
#
# This selection includes:
# - T cells
# - NK cells
# - B cells
# - Plasma cells
# - Monocytes
# - Macrophages
# - Dendritic cells
# - Neutrophils
# - Mast cells
#
# The pattern is retained from the original source workflow.

immune_pattern <- paste(
  "T cell",
  "NK",
  "B cell",
  "plasma",
  "monocyte",
  "macrophage",
  "dendritic",
  "DC",
  "neutrophil",
  "mast",
  sep = "|"
)


# Identify cells matching the broad immune-cell labels.

immune_cells <- colnames(obj)[
  
  grepl(
    immune_pattern,
    obj$SingleR_label,
    ignore.case = TRUE
  )
]


# Check whether any cells were selected.

if (length(immune_cells) == 0) {
  
  stop(
    "No cells matched the broad immune-cell label pattern. ",
    "Review SingleR labels before proceeding."
  )
}


# Extract the broad immune-cell subset.

immune <- subset(
  
  obj,
  
  cells = immune_cells
)


############################################################
# 12. Summarize Broad Immune-Cell Composition
############################################################

# Calculate the number of cells assigned to each SingleR
# label within the broad immune-cell subset.

immune_summary <- as.data.frame(
  table(immune$SingleR_label)
)

colnames(immune_summary) <- c(
  "SingleR_label",
  "Cells"
)


# Save immune-cell subset composition.

write.csv(
  
  immune_summary,
  
  out_dir(
    "annotation",
    "04_immune_subset_composition.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 13. Save Annotated Seurat Object
############################################################

# Save the broad immune-cell subset with:
# - Original cell-level metadata
# - Global cluster identities
# - SingleR predicted labels
# - SingleR pruned labels
# - Normalized expression and dimensional reductions

saveRDS(
  
  immune,
  
  out_dir(
    "rds",
    "04_HGSOC_immune_SingleR.rds"
  )
)


