  cells_before = ncol(HGSOC),
  
  cells_after = ncol(HGSOC_QC),
  
  cells_removed = ncol(HGSOC) - ncol(HGSOC_QC),
  
  percent_retained = round(
    ncol(HGSOC_QC) / ncol(HGSOC) * 100,
