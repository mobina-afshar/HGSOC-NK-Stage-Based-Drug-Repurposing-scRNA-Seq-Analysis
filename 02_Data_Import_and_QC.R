############################################################
# 11. Evaluate Mitochondrial Threshold Sensitivity
############################################################

# Evaluate cell retention across the mitochondrial percentage
# thresholds defined in config.yaml.
#
# All other QC criteria remain unchanged during this analysis.

mt_thresholds <- unlist(
  cfg$qc$mt_sensitivity_thresholds
)

qc_sensitivity <- do.call(
  
  rbind,
  
  lapply(
    mt_thresholds,
    
    function(mt) {
      
      keep <- with(
        
        HGSOC@meta.data,
        
        nFeature_RNA > cfg$qc$min_features &
          
          nFeature_RNA < cfg$qc$max_features &
          
          nCount_RNA < cfg$qc$max_counts &
          
          percent.mt < mt
      )
      
      
      data.frame(
        
        max_percent_mt = mt,
        
        total_cells = length(keep),
        
        retained_cells = sum(keep),
        
        percent_retained = round(
          mean(keep) * 100,
          2
        )
      )
    }
  )
)


# Save mitochondrial threshold sensitivity results.

write.csv(
  
  qc_sensitivity,
  
  out_dir(
    "qc",
    "04_qc_mitochondrial_threshold_sensitivity.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 12. Apply Quality Control Filters
############################################################

# Retain cells satisfying all configured QC criteria:
#
# - Minimum detected genes
# - Maximum detected genes
# - Maximum total RNA counts
# - Maximum mitochondrial transcript percentage

HGSOC_QC <- subset(
  
  HGSOC,
  
  subset =
    
    nFeature_RNA > cfg$qc$min_features &
    
    nFeature_RNA < cfg$qc$max_features &
    
    nCount_RNA < cfg$qc$max_counts &
    
    percent.mt < cfg$qc$max_percent_mt
)


############################################################
# 13. Summarize Overall Cell Retention
############################################################

# Calculate the number and percentage of cells retained
