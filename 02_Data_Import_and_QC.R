# Read each sample independently and attach its clinical
# metadata before merging.

read_one_sample <- function(i) {
  
  gsm <- sample_metadata$GSM[i]
  
  sid <- sample_metadata$sample[i]
  
  prefix <- paste0(
    gsm,
    "_",
    sid
  )
  
  
  # Define the expected 10x input files.
  
  paths <- list(
    
    mtx = file.path(
      RAW_DIR,
      paste0(prefix, ".matrix.mtx.gz")
    ),
    
    barcodes = file.path(
      RAW_DIR,
      paste0(prefix, ".barcodes.tsv.gz")
    ),
    
    features = file.path(
      RAW_DIR,
      paste0(prefix, ".genes.tsv.gz")
    )
  )
  
  
  # Check that all required input files exist.
  
  input_files <- unlist(paths)
  
  absent_files <- input_files[
    !file.exists(input_files)
  ]
  
  if (length(absent_files) > 0) {
    
    stop(
      "Missing 10x input file(s): ",
      paste(absent_files, collapse = "; ")
    )
  }
  
  
  # Read the 10x count matrix.
  
  counts <- ReadMtx(
    
    mtx = paths$mtx,
    
    cells = paths$barcodes,
    
    features = paths$features,
    
    feature.column = 2,
    
    cell.column = 1,
    
    unique.features = TRUE
  )
  
  
  # Create a Seurat object using the configured QC threshold.
  
  obj <- CreateSeuratObject(
    
    counts = counts,
    
    min.cells = 3,
    
    min.features = cfg$qc$min_features,
    
    project = cfg$project$id
  )
  
  
  # Attach sample-level metadata.
  
  obj$sample <- sid
  
  obj$GSM <- gsm
  
  obj$stage <- sample_metadata$stage[i]
  
  obj$stage_group <- sample_metadata$stage_group[i]
  
  
  return(obj)
}


