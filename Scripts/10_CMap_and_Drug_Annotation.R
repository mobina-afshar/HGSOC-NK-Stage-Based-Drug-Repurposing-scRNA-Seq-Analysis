
############################################################
# GSE184880 - HGSOC scRNA-seq Analysis
# Script 10: CMap Signature Generation and Drug Annotation
#
# Workflow:
# Stage-Based Drug Repurposing in High-Grade Serous
# Ovarian Cancer
#
# Primary Cell Population:
# - Cluster 0: NK-like cells
#
# Differential Expression Comparison:
# - Late vs Early
#
# CMap Signature Strategy:
# - Rank genes using DESeq2 Wald statistics.
# - Positive statistics represent genes upregulated in Late.
# - Negative statistics represent genes upregulated in Early.
# - Generate a two-sided gene signature.
#
# Input Files:
# - config.yaml
# - results/rds/DESeq2_Results_All_Populations.rds
# - Optional: results/cmap/CMap_results.xlsx
#
# Output Files:
# - Two-sided CMap gene signatures.
# - Selected gene-level DESeq2 statistics.
# - CMap signature summary.
# - Imported external CMap results.
# - CMap candidate compound figures.
# - Session information.
#
# Important Notes:
# - The signature is derived from DESeq2 results.
# - GSEA leading-edge genes are not used.
# - Significant DEG filtering is not applied.
# - External CMap and drug annotation data must be
#   obtained and verified independently.
############################################################


############################################################
# 1. Load Project Configuration
############################################################

# Check whether the project configuration file exists.

if (!file.exists("config.yaml")) {
  stop(
    "config.yaml was not found. ",
    "Run this script from the project root."
  )
}


# Check whether the required configuration package is installed.

if (!requireNamespace("yaml", quietly = TRUE)) {
  stop(
    "Package 'yaml' is required. ",
    "Install it using install.packages('yaml')."
  )
}


# Load project configuration.

cfg <- yaml::read_yaml("config.yaml")


# Define project directories.

PROJECT_ROOT <- normalizePath(
  getwd(),
  winslash = "/",
  mustWork = TRUE
)

RESULTS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$results
)

LOGS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$logs
)

RDS_DIR <- file.path(
  RESULTS_DIR,
  "rds"
)


# Create required output directories.

dir.create(
  RESULTS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  LOGS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  RDS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)


# Set the project-wide random seed.

set.seed(cfg$project$seed)


############################################################
# 2. Define Shared Helper Functions
############################################################

# Generate output file paths and create parent directories.

output_file <- function(...) {
  
  path <- file.path(
    RESULTS_DIR,
    ...
  )
  
  dir.create(
    dirname(path),
    recursive = TRUE,
    showWarnings = FALSE
  )
  
  return(path)
}


# Save R session information for reproducibility.

save_session <- function(tag) {
  
  capture.output(
    sessionInfo(),
    file = file.path(
      LOGS_DIR,
      paste0(tag, "_sessionInfo.txt")
    )
  )
}


############################################################
# 3. Validate CMap Configuration
############################################################

# Check whether the requested signature size is specified.

if (is.null(cfg$cmap$genes_per_direction)) {
  stop(
    "Missing configuration: ",
    "cmap$genes_per_direction in config.yaml."
  )
}


# Retrieve the number of genes to select in each direction.

n_each <- cfg$cmap$genes_per_direction


# Validate the requested signature size.

if (
  length(n_each) != 1 ||
  !is.numeric(n_each) ||
  !is.finite(n_each) ||
  n_each < 1 ||
  n_each != as.integer(n_each)
) {
  stop(
    "cmap$genes_per_direction must be a positive integer."
  )
}


n_each <- as.integer(n_each)


message(
  "CMap genes per direction: ",
  n_each
)


############################################################
# 4. Load DESeq2 Results
############################################################

# Define the combined DESeq2 results file generated by Script 08.

de_file <- file.path(
  RDS_DIR,
  "DESeq2_Results_All_Populations.rds"
)


# Check whether the DESeq2 results file exists.

if (!file.exists(de_file)) {
  stop(
    "DESeq2 results were not found: ",
    de_file,
    "\nRun Script 08 first and verify the RDS output path."
  )
}


# Load the combined DESeq2 results.

de_list <- readRDS(de_file)


# Check whether NK-like results are available.

if (!"NK-like" %in% names(de_list)) {
  stop(
    "NK-like results were not found in the DESeq2 RDS object."
  )
}


# Validate the expected structure of the NK-like results.

if (is.null(de_list[["NK-like"]]$results)) {
  stop(
    "The expected structure ",
    "de_list[['NK-like']]$results is missing."
  )
}


# Extract NK-like DESeq2 results.

nk <- as.data.frame(
  de_list[["NK-like"]]$results
)


# Define the required DESeq2 result columns.

required_columns <- c(
  "gene",
  "stat",
  "log2FoldChange",
  "pvalue",
  "padj"
)


# Check for missing columns.

missing_columns <- setdiff(
  required_columns,
  colnames(nk)
)

if (length(missing_columns) > 0) {
  stop(
    "Missing columns in NK-like DESeq2 results: ",
    paste(missing_columns, collapse = ", ")
  )
}


message(
  "Loaded NK-like DESeq2 results: ",
  nrow(nk),
  " genes."
)


############################################################
# 5. Prepare DESeq2 Gene Ranking
############################################################

# Use all genes with valid Wald statistics.
# Do not restrict the ranking to statistically significant DEGs.


# Standardize gene identifiers.

nk$gene <- trimws(
  as.character(nk$gene)
)


# Remove genes with missing identifiers or invalid Wald statistics.

nk <- nk[
  !is.na(nk$gene) &
    nzchar(nk$gene) &
    is.finite(nk$stat),
  ,
  drop = FALSE
]


# Check whether any valid genes remain.

if (nrow(nk) == 0) {
  stop(
    "No genes with valid gene names and Wald statistics were found."
  )
}


# Verify that gene identifiers are compatible with CMap.
# Ensembl identifiers must be mapped to gene symbols first.

if (any(grepl("^ENSG", nk$gene))) {
  stop(
    "Ensembl gene IDs were detected in the gene column. ",
    "Map them to HGNC gene symbols before generating ",
    "the CMap signature."
  )
}


# Check for duplicated gene symbols.

if (anyDuplicated(nk$gene)) {
  stop(
    "Duplicate gene symbols were detected. ",
    "Resolve duplicated symbols before generating ",
    "the CMap signature."
  )
}


# Rank genes by DESeq2 Wald statistic.
# Positive values indicate higher expression in Late.
# Negative values indicate higher expression in Early.

nk <- nk[
  order(
    -nk$stat,
    nk$gene
  ),
  ,
  drop = FALSE
]


message(
  "Genes available for CMap ranking: ",
  nrow(nk)
)


############################################################
# 6. Generate Two-Sided CMap Gene Signature
############################################################

# Identify genes upregulated in Late.
# Select genes with positive Wald statistics.

late_candidates <- nk[
  nk$stat > 0,
  ,
  drop = FALSE
]


# Select the top-ranked genes in the positive direction.

late_genes <- head(
  late_candidates$gene,
  n_each
)


# Identify genes upregulated in Early.
# These genes are downregulated in Late.

early_candidates <- nk[
  nk$stat < 0,
  ,
  drop = FALSE
]


# Rank negative Wald statistics from most negative to least negative.

early_candidates <- early_candidates[
  order(
    early_candidates$stat,
    early_candidates$gene
  ),
  ,
  drop = FALSE
]


# Select the top-ranked genes in the negative direction.

early_genes <- head(
  early_candidates$gene,
  n_each
)


# Verify that both signature directions contain genes.

if (
  length(late_genes) == 0 ||
  length(early_genes) == 0
) {
  stop(
    "The two-sided signature could not be generated. ",
    "Check the distribution of positive and negative ",
    "Wald statistics."
  )
}


# Issue a warning if fewer genes than requested are available.

if (
  length(late_genes) < n_each ||
  length(early_genes) < n_each
) {
  warning(
    "Fewer genes than requested were available ",
    "in one or both directions."
  )
}


############################################################
# 7. Export CMap Gene Signature Files
############################################################

# Combine the UP and DOWN gene lists.

signature <- data.frame(
  
  Gene = c(
    late_genes,
    early_genes
  ),
  
  Direction = c(
    
    rep(
      "UP_in_Late",
      length(late_genes)
    ),
    
    rep(
      "DOWN_in_Late",
      length(early_genes)
    )
  ),
  
  stringsAsFactors = FALSE
)


# Export genes upregulated in Late.

writeLines(
  late_genes,
  output_file(
    "cmap",
    "01_NK_like_UP_in_Late.txt"
  )
)


# Export genes downregulated in Late.

writeLines(
  early_genes,
  output_file(
    "cmap",
    "02_NK_like_DOWN_in_Late.txt"
  )
)


# Export the combined two-sided CMap signature.

write.csv(
  signature,
  output_file(
    "cmap",
    "03_NK_like_CMap_two_sided_signature.csv"
  ),
  row.names = FALSE
)


############################################################
# 8. Export DESeq2 Statistics for Selected Genes
############################################################

# Combine genes selected from both signature directions.

selected_genes <- c(
  late_genes,
  early_genes
)


# Retrieve the corresponding DESeq2 statistics.

detail <- nk[
  match(
    selected_genes,
    nk$gene
  ),
  ,
  drop = FALSE
]


# Retain the required statistical columns.

detail <- detail[
  ,
  c(
    "gene",
    "stat",
    "log2FoldChange",
    "pvalue",
    "padj"
  ),
  drop = FALSE
]


# Rename the gene identifier column.

colnames(detail)[1] <- "Gene"


# Assign the signature direction using the Wald statistic.

detail$Direction <- ifelse(
  detail$stat > 0,
  "UP_in_Late",
  "DOWN_in_Late"
)


# Record the order of genes in the two-sided signature.

detail$Signature_Rank <- seq_len(
  nrow(detail)
)


# Export selected genes with their DESeq2 statistics.

write.csv(
  detail,
  output_file(
    "cmap",
    "04_NK_like_CMap_signature_with_DESeq2_statistics.csv"
  ),
  row.names = FALSE
)


############################################################
# 9. Export CMap Signature Summary
############################################################

# Summarize the number of genes selected in each direction.

signature_summary <- data.frame(
  
  Population = "NK-like",
  
  Comparison = "Late_vs_Early",
  
  UP_in_Late = length(late_genes),
  
  DOWN_in_Late = length(early_genes),
  
  Total_signature_genes = nrow(signature),
  
  stringsAsFactors = FALSE
)


# Export the signature summary.

write.csv(
  signature_summary,
  output_file(
    "cmap",
    "05_CMap_signature_size.csv"
  ),
  row.names = FALSE
)


# Report the signature composition.

message(
  "CMap signature successfully generated."
)

message(
  "UP in Late: ",
  length(late_genes)
)

message(
  "DOWN in Late: ",
  length(early_genes)
)


############################################################
# 10. Import External CMap Results
############################################################

# Submit the exported signature files to the external CMap platform.
# Save the downloaded results as:
# results/cmap/CMap_results.xlsx
#
# This script does not automatically query the external platform
# or generate compound connectivity scores.


# Define the external CMap results file.

cmap_results_path <- output_file(
  "cmap",
  "CMap_results.xlsx"
)


# Import external CMap results when the Excel file is available.

if (file.exists(cmap_results_path)) {
  
  # Check whether the required Excel import package is installed.
  
  if (!requireNamespace("readxl", quietly = TRUE)) {
    stop(
      "Package 'readxl' is required to import CMap_results.xlsx. ",
      "Install it using install.packages('readxl')."
    )
  }
  
  
  # Import the external CMap results.
  
  cmap <- readxl::read_xlsx(
    cmap_results_path
  )
  
  
  # Check whether the imported results contain data.
  
  if (nrow(cmap) == 0) {
    
    stop(
      "CMap_results.xlsx exists but contains no data."
    )
    
  }
  
  
  # Export a standardized copy of the imported results.
  
  write.csv(
    cmap,
    output_file(
      "cmap",
      "06_CMap_results_imported.csv"
    ),
    row.names = FALSE
  )
  
  
  message(
    "External CMap results imported successfully."
  )
  
} else {
  
  message(
    "CMap_results.xlsx not found. ",
    "Signature files are ready for external submission."
  )
}


############################################################
# 11. Validate CMap Results for Visualization
############################################################

# CMap results are required for candidate compound visualization.

if (!exists("cmap")) {
  stop(
    "External CMap results are not available. ",
    "Submit the signature to CMap and save the results as ",
    "results/cmap/CMap_results.xlsx before running this section."
  )
}


# Load visualization and data-processing packages.

required_packages <- c(
  "ggplot2",
  "dplyr"
)


# Check whether all required packages are installed.

missing_packages <- required_packages[
  !vapply(
    required_packages,
    requireNamespace,
    logical(1),
    quietly = TRUE
  )
]


if (length(missing_packages) > 0) {
  stop(
    "The following packages are required: ",
    paste(missing_packages, collapse = ", "),
    ". Install them before running this section."
  )
}


library(ggplot2)
library(dplyr)


# Validate the required columns.

required_cols <- c(
  "Name",
  "Score"
)


missing_cols <- setdiff(
  required_cols,
  colnames(cmap)
)


if (length(missing_cols) > 0) {
  
  stop(
    "Missing required CMap columns: ",
    paste(missing_cols, collapse = ", "),
    ". Check colnames(cmap)."
  )
}


############################################################
# 12. Prepare CMap Candidate Compounds
############################################################

# Standardize compound names and connectivity scores.

cmap <- cmap %>%
  mutate(
    Name = as.character(Name),
    Score = as.numeric(Score)
  ) %>%
  filter(
    !is.na(Name),
    Name != "",
    !is.na(Score)
  )


# Select compounds with strong negative connectivity scores.

cmap_selected <- cmap %>%
  filter(
    Score <= -90
  ) %>%
  arrange(Score)


# Stop if no compounds meet the selection threshold.

if (nrow(cmap_selected) == 0) {
  
  stop(
    "No compounds passed the connectivity threshold of <= -90."
  )
}


# Set compound display order according to connectivity score.

cmap_selected <- cmap_selected %>%
  mutate(
    Name = factor(
      Name,
      levels = unique(Name)
    )
  )


# Determine the x-axis limits from the selected scores.

x_min <- min(cmap_selected$Score)
x_max <- -90


############################################################
# 13. Plot CMap Candidate Compounds
############################################################

# Generate a horizontal bar-style plot of negative connectivity scores.

p_cmap <- ggplot(
  cmap_selected,
  aes(
    y = Name,
    x = Score,
    color = Score
  )
) +
  
  geom_segment(
    aes(
      x = x_max,
      xend = Score,
      yend = Name
    ),
    linewidth = 8,
    lineend = "butt"
  ) +
  
  scale_color_gradient(
    low = "#A8DAD3",
    high = "#075457",
    name = "CMap Score"
  ) +
  
  scale_x_continuous(
    limits = c(
      x_min - 0.5,
      x_max
    ),
    breaks = pretty(
      c(x_min, x_max),
      n = 5
    ),
    expand = c(0, 0)
  ) +
  
  labs(
    title = "CMap-Prioritized Drug Candidates",
    x = "Connectivity Score",
    y = NULL
  ) +
  
  theme_classic(
    base_size = 13
  ) +
  
  theme(
    plot.title = element_text(
      face = "bold",
      size = 16
    ),
    axis.title.x = element_text(
      face = "bold"
    ),
    axis.line = element_line(
      color = "#8AAEAA"
    ),
    axis.ticks = element_line(
      color = "#8AAEAA"
    ),
    legend.position = "right"
  )


# Display the CMap candidate compound plot.

print(p_cmap)


