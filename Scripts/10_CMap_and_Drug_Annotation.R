
############################################################
# GSE184880 - HGSOC scRNA-seq Analysis
# Script 10: CMap Signature and Drug Annotation
#
# Workflow: Stage-Based Drug Repurposing in HGSOC
#
# Purpose:
# Generate a two-sided CMap gene signature from NK-like
# patient-level pseudobulk DESeq2 results and prepare
# external drug annotation files.
#
# Primary population:
# - Cluster 0 -> NK-like
#
# Comparison:
# - Late vs Early
#
# CMap signature:
# - DESeq2 Wald-statistic ranking
# - UP in Late
# - DOWN in Late
#
# Input:
# - config.yaml
# - results/rds/DESeq2_Results_All_Populations.rds
# - Optional: results/cmap/CMap_results.csv
#
# Output:
# - Two-sided CMap signature files
# - Selected gene statistics
# - Signature size summary
# - Imported external CMap results (if supplied)
# - DGIdb annotation template
# - DrugBank annotation template
# - logs/10_CMap_Drug_Annotation_sessionInfo.txt
#
# IMPORTANT:
# - The CMap signature is derived from DESeq2 results.
# - GSEA leading-edge genes are NOT used.
# - Significant DEG filtering is NOT applied.
# - Positive Wald statistics indicate higher expression in Late.
# - Negative Wald statistics indicate higher expression in Early.
# - CMap and drug annotations require external data retrieval.
############################################################


############################################################
# 1. Load Project Configuration
############################################################

if (!file.exists("config.yaml")) {
  
  stop(
    "config.yaml was not found. ",
    "Run this script from the project root."
  )
}


if (!requireNamespace("yaml", quietly = TRUE)) {
  
  stop(
    "Package 'yaml' is required. ",
    "Install it using install.packages('yaml')."
  )
}


# Read project configuration.

cfg <- yaml::read_yaml("config.yaml")


# Define project directories.

PROJECT_ROOT <- normalizePath(
  getwd(),
  winslash = "/",
  mustWork = TRUE
)

RESULTS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$results
)

LOGS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$logs
)

RDS_DIR <- file.path(
  RESULTS_DIR,
  "rds"
)


# Create required output directories.

dir.create(
  RESULTS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  LOGS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  RDS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)


# Set project-wide random seed.

set.seed(cfg$project$seed)


############################################################
# 2. Define Shared Helper Functions
############################################################

# Generate output file paths and create parent directories.

output_file <- function(...) {
  
  path <- file.path(
    RESULTS_DIR,
    ...
  )
  
  dir.create(
    dirname(path),
    recursive = TRUE,
    showWarnings = FALSE
  )
  
  return(path)
}


# Save R session information for reproducibility.

save_session <- function(tag) {
  
  capture.output(
    sessionInfo(),
    file = file.path(
      LOGS_DIR,
      paste0(tag, "_sessionInfo.txt")
    )
  )
}


############################################################
# 3. Validate CMap Configuration
############################################################

# Check whether the number of genes per direction
# is specified in config.yaml.

if (is.null(cfg$cmap$genes_per_direction)) {
  
  stop(
    "Missing configuration: ",
    "cmap$genes_per_direction in config.yaml."
  )
}


# Load the number of genes to select in each direction.

n_each <- cfg$cmap$genes_per_direction


# Validate the requested signature size.

if (
  length(n_each) != 1 ||
  is.na(n_each) ||
  !is.numeric(n_each) ||
  n_each < 1 ||
  n_each != as.integer(n_each)
) {
  
  stop(
    "cmap$genes_per_direction must be a positive integer."
  )
}


n_each <- as.integer(n_each)


message(
  "CMap genes per direction: ",
  n_each
)


############################################################
# 4. Load DESeq2 Results
############################################################

# Define the combined DESeq2 results file.
#
# This file is generated by Script 08 and must be
# located in results/rds/.

de_file <- file.path(
  RDS_DIR,
  "DESeq2_Results_All_Populations.rds"
)


# Check whether the DESeq2 results file exists.

if (!file.exists(de_file)) {
  
  stop(
    "DESeq2 results were not found: ",
    de_file,
    "\nRun Script 08 first and verify the RDS output path."
  )
}


# Load the complete DESeq2 result list.

de_list <- readRDS(de_file)


# Check whether NK-like results are available.

if (!"NK-like" %in% names(de_list)) {
  
  stop(
    "NK-like results were not found in the DESeq2 RDS object."
  )
}


# Validate the expected result-list structure.

if (is.null(de_list[["NK-like"]]$results)) {
  
  stop(
    "The expected structure ",
    "de_list[['NK-like']]$results is missing."
  )
}


# Extract NK-like DESeq2 results.

nk <- as.data.frame(
  de_list[["NK-like"]]$results
)


# Define required columns.

required_columns <- c(
  "gene",
  "stat",
  "log2FoldChange",
  "pvalue",
  "padj"
)


# Check for missing columns.

missing_columns <- setdiff(
  required_columns,
  colnames(nk)
)

if (length(missing_columns) > 0) {
  
  stop(
    "Missing columns in NK-like DESeq2 results: ",
    paste(missing_columns, collapse = ", ")
  )
}


message(
  "Loaded NK-like DESeq2 results: ",
  nrow(nk),
  " genes."
)


############################################################
# 5. Prepare DESeq2 Gene Ranking
############################################################

# Use all genes with valid Wald statistics.
# Do not restrict the signature to significant DEGs.


# Standardize gene identifiers.

nk$gene <- trimws(
  as.character(nk$gene)
)


# Remove genes with missing identifiers or invalid
# Wald statistics.

nk <- nk[
  !is.na(nk$gene) &
    nzchar(nk$gene) &
    is.finite(nk$stat),
  ,
  drop = FALSE
]


# Check whether any valid genes remain.

if (nrow(nk) == 0) {
  
  stop(
    "No genes with valid gene names and Wald statistics were found."
  )
}


# CMap requires gene symbols.
# Stop if Ensembl-style identifiers are detected.

if (any(grepl("^ENSG", nk$gene))) {
  
  stop(
    "Ensembl gene IDs were detected in the gene column. ",
    "Map them to HGNC gene symbols before generating ",
    "the CMap signature."
  )
}


# Check for duplicated gene symbols.

if (anyDuplicated(nk$gene)) {
  
  stop(
    "Duplicate gene symbols were detected. ",
    "Resolve duplicated symbols before generating ",
    "the CMap signature."
  )
}


# Rank genes by DESeq2 Wald statistic.
#
# Positive stat: higher expression in Late.
# Negative stat: higher expression in Early.

nk <- nk[
  order(
    -nk$stat,
    nk$gene
  ),
  ,
  drop = FALSE
]


message(
  "Genes available for CMap ranking: ",
  nrow(nk)
)


############################################################
# 6. Generate Two-Sided CMap Signature
############################################################

# UP in Late:
# Select genes with positive DESeq2 Wald statistics.


late_candidates <- nk[
  nk$stat > 0,
  ,
  drop = FALSE
]


# Select the top-ranked genes in the positive direction.

late_genes <- head(
  late_candidates$gene,
  n_each
)


# DOWN in Late:
# Select genes with negative DESeq2 Wald statistics.
# These genes are relatively higher in Early.

early_candidates <- nk[
  nk$stat < 0,
  ,
  drop = FALSE
]


# Rank negative Wald statistics from most negative
# to least negative.

early_candidates <- early_candidates[
  order(
    early_candidates$stat,
    early_candidates$gene
  ),
  ,
  drop = FALSE
]


# Select the top-ranked genes in the negative direction.

early_genes <- head(
  early_candidates$gene,
  n_each
)


# Check whether both directions are represented.

if (
  length(late_genes) == 0 ||
  length(early_genes) == 0
) {
  
  stop(
    "The two-sided signature could not be generated. ",
    "Check the distribution of positive and negative ",
    "Wald statistics."
  )
}


# Warn if fewer genes than requested are available.

if (
  length(late_genes) < n_each ||
  length(early_genes) < n_each
) {
  
  warning(
    "Fewer genes than requested were available ",
    "in one or both directions."
  )
}


############################################################
# 7. Save CMap Signature Files
############################################################

# Combine UP and DOWN gene lists.

signature <- data.frame(
  
  Gene = c(
    late_genes,
    early_genes
  ),
  
  Direction = c(
    
    rep(
      "UP_in_Late",
      length(late_genes)
    ),
    
    rep(
      "DOWN_in_Late",
      length(early_genes)
    )
  ),
  
  stringsAsFactors = FALSE
)


# Save separate gene lists for external CMap submission.

writeLines(
  
  late_genes,
  
  output_file(
    "cmap",
    "01_NK_like_UP_in_Late.txt"
  )
)


writeLines(
  
  early_genes,
  
  output_file(
    "cmap",
    "02_NK_like_DOWN_in_Late.txt"
  )
)


# Save the combined two-sided signature.

write.csv(
  
  signature,
  
  output_file(
    "cmap",
    "03_NK_like_CMap_two_sided_signature.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 8. Save DESeq2 Statistics for Selected Genes
############################################################

# Combine selected genes from both directions.

selected_genes <- c(
  late_genes,
  early_genes
)


# Retrieve the corresponding DESeq2 statistics.

detail <- nk[
  match(
    selected_genes,
    nk$gene
  ),
  ,
  drop = FALSE
]


# Retain the required statistical columns.

detail <- detail[
  ,
  c(
    "gene",
    "stat",
    "log2FoldChange",
    "pvalue",
    "padj"
  ),
  drop = FALSE
]


# Rename the gene identifier column.

colnames(detail)[1] <- "Gene"


# Assign direction based on the Wald statistic.

detail$Direction <- ifelse(
  detail$stat > 0,
  "UP_in_Late",
  "DOWN_in_Late"
)


# Record the order of genes in the two-sided signature.

detail$Signature_Rank <- seq_len(
  nrow(detail)
)


# Export selected genes with their DESeq2 statistics.

write.csv(
  
  detail,
  
  output_file(
    "cmap",
    "04_NK_like_CMap_signature_with_DESeq2_statistics.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 9. Save CMap Signature Summary
############################################################

signature_summary <- data.frame(
  
  Population = "NK-like",
  
  Comparison = "Late_vs_Early",
  
  UP_in_Late = length(late_genes),
  
  DOWN_in_Late = length(early_genes),
  
  Total_signature_genes = nrow(signature),
  
  stringsAsFactors = FALSE
)


# Export signature size summary.

write.csv(
  
  signature_summary,
  
  output_file(
    "cmap",
    "05_CMap_signature_size.csv"
  ),
  
  row.names = FALSE
)


# Display signature summary.

message(
  "CMap signature successfully generated."
)

message(
  "UP in Late: ",
  length(late_genes)
)

message(
  "DOWN in Late: ",
  length(early_genes)
)


############################################################
# 10. Import External CMap Results
############################################################

# Submit the signature files to the external CMap platform.
#
# Save the downloaded result table as:
# results/cmap/CMap_results.csv
#
# This script does not fabricate compound scores or
# automatically query the external CMap platform.


cmap_results_path <- output_file(
  "cmap",
  "CMap_results.csv"
)


# Import external CMap results if the file is available.

if (file.exists(cmap_results_path)) {
  
  cmap <- read.csv(
    
    cmap_results_path,
    
    check.names = FALSE,
    
    stringsAsFactors = FALSE
  )
  
  
  # Check whether the imported table contains data.
  
  if (nrow(cmap) == 0) {
    
    warning(
      "CMap_results.csv exists but contains no data."
    )
    
  } else {
    
    # Save a standardized copy of the imported results.
    
    write.csv(
      
      cmap,
      
      output_file(
        "cmap",
        "06_CMap_results_imported.csv"
      ),
      
      row.names = FALSE
    )
    
    
    message(
      "External CMap results imported. ",
      "Review compound names, scores, and connectivity directions."
    )
  }
  
} else {
  
  message(
    "CMap_results.csv not found. ",
    "Signature files are ready for external submission."
  )
}


############################################################
# 11. Create DGIdb and DrugBank Annotation Templates
############################################################

# These files are templates for verified external annotations.
# They do not represent actual drug-gene interactions.


# Define DGIdb annotation template.

dgidb_template <- data.frame(
  
  Drug = character(),
  
  Gene = character(),
  
  Interaction = character(),
  
  Source = character(),
  
  stringsAsFactors = FALSE
)


# Define DrugBank annotation template.

drugbank_template <- data.frame(
  
  Drug = character(),
  
  DrugBank_ID = character(),
  
  Mechanism = character(),
  
  Indication = character(),
  
  Clinical_Status = character(),
  
  Source_URL = character(),
  
  stringsAsFactors = FALSE
)


# Define annotation file paths.

dgidb_file <- output_file(
  "drug_annotation",
  "DGIdb_interactions.csv"
)

drugbank_file <- output_file(
  "drug_annotation",
  "DrugBank_annotations.csv"
)


# Create DGIdb template only if it does not already exist.

if (!file.exists(dgidb_file)) {
  
  write.csv(
    
    dgidb_template,
    
    dgidb_file,
    
    row.names = FALSE
  )
  
  message(
    "Created DGIdb annotation template."
  )
}


# Create DrugBank template only if it does not already exist.

if (!file.exists(drugbank_file)) {
  
  write.csv(
    
    drugbank_template,
    
    drugbank_file,
    
    row.names = FALSE
  )
  
  message(
    "Created DrugBank annotation template."
  )
}


