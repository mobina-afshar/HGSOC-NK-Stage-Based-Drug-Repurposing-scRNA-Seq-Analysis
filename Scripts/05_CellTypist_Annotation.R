#   results/rds/05_HGSOC_immune_CellTypist.rds
# - Python environment information
# - R session information
#
# IMPORTANT:
# - The input is the broad immune-cell subset generated by Script 04.
# - CellTypist annotation is performed in batches to reduce memory use.
# - majority_voting = FALSE is retained from the original workflow.
# - CellTypist confidence is calculated as the maximum prediction
#   probability for each cell.
# - The active Python environment must contain the required
#   CellTypist dependencies.
############################################################


