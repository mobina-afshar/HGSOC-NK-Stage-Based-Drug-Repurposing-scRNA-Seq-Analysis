  )
)

library(Seurat)
library(reticulate)
library(Matrix)


############################################################
# 4. Load SingleR-Derived Immune-Cell Subset
############################################################

# Load the broad immune-cell subset generated by Script 04.

input_rds <- out_dir(
  "rds",
  "04_HGSOC_immune_SingleR.rds"
)

if (!file.exists(input_rds)) {
  
  stop(
    "Run Script 04 first. Missing input file: ",
    input_rds
  )
}


obj <- readRDS(input_rds)


# Set the RNA assay as the default assay.

DefaultAssay(obj) <- "RNA"


############################################################
# 5. Check and Record the Active Python Environment
############################################################

# Display the active Python configuration.

py_config()

py_discover_config()


# Install the required Python packages in the active
# reticulate environment.
#
# IMPORTANT:
# This step may modify the active Python environment.
# It does not explicitly select or switch to another environment.

py_install(
  
  packages = c(
    "celltypist",
    "anndata",
    "numpy",
    "pandas"
  ),
  
  pip = TRUE
)


# Save Python environment information for reproducibility.

capture.output(
  
  py_config(),
  
  file = file.path(
    LOGS_DIR,
    "05_reticulate_python_config.txt"
  )
)


############################################################
# 6. Verify Python Dependencies
############################################################

# Check that the required Python modules are available
# in the active reticulate environment.

required_python_modules <- c(
  "celltypist",
  "anndata",
  "numpy",
  "pandas"
)


for (module in required_python_modules) {
  
  if (!py_module_available(module)) {
    
    stop(
      "Python module '",
      module,
      "' is unavailable in the reticulate environment. ",
      "Install CellTypist dependencies in the Python ",
      "environment shown in the log file."
    )
  }
}


# Import required Python modules.

celltypist <- import("celltypist")

anndata <- import("anndata")


############################################################
# 7. Download the CellTypist Reference Model
############################################################

# Download the Immune_All_High reference model.

# The model used for annotation is specified in config.yaml.

py_run_string(
  "
from celltypist import models
models.download_models(model='Immune_All_High.pkl')
"
)


# Retrieve the configured CellTypist model name.

model_name <- cfg$celltypist$model


############################################################
# 8. Prepare Expression Matrix for CellTypist
############################################################

# Extract normalized RNA expression data.
#
# The data layer contains LogNormalize-transformed expression
# values generated in Script 03.

expr <- GetAssayData(
  
  obj,
  
  assay = "RNA",
  
  layer = "data"
)


# Extract cell identifiers.

cell_ids <- colnames(expr)


# Retrieve batch size from project configuration.

batch_size <- cfg$celltypist$batch_size


# Divide cells into batches to reduce memory consumption.

batches <- split(
  
  cell_ids,
  
  ceiling(
    seq_along(cell_ids) / batch_size
  )
)


# Initialize a list to store batch-wise predictions.

prediction_list <- vector(
  
  "list",
  
  length(batches)
)


############################################################
# 9. Run CellTypist Annotation Batch by Batch
############################################################

# Process each batch independently.

for (i in seq_along(batches)) {
  
  message(
    "Processing CellTypist batch ",
    i,
    " of ",
    length(batches)
  )
  
  
  # Identify cells in the current batch.
  
  cells_i <- batches[[i]]
  
  
  # Extract the expression matrix for the current batch.
  #
  # CellTypist expects cells as rows and genes as columns.
  
  mat_i <- t(
    as.matrix(
      expr[
        ,
        cells_i,
        drop = FALSE
      ]
    )
  )
  
  
  # Convert the expression matrix into an AnnData object.
  
  adata_i <- anndata$AnnData(
    X = mat_i
  )
  
  
  # Assign cell and gene identifiers.
  
  adata_i$obs_names <- cells_i
  
  adata_i$var_names <- rownames(expr)
  
  
  # Transfer the AnnData object and model name to Python.
  
  py$adata_i <- adata_i
  
  py$model_name <- model_name
  
  
  # Run CellTypist annotation in Python.
  #
  # majority_voting = FALSE:
  # Retain individual cell-level predictions.
  #
  # mode = 'best match':
  # Use the best-matching cell type prediction.
  
  py_run_string(
    "
import celltypist

pred_i = celltypist.annotate(
    adata_i,
    model=model_name,
    majority_voting=False,
    mode='best match'
)

labels_i = pred_i.predicted_labels

conf_i = pred_i.probability_matrix.max(axis=1)
"
  )


# Transfer predictions from Python to R.

labels_i <- py_to_r(
  py$labels_i
)

conf_i <- as.numeric(
  py_to_r(py$conf_i)
)


# Construct the batch-level prediction table.

batch_df <- data.frame(
  
  cell = rownames(labels_i),
  
  CellTypist_label = labels_i$predicted_labels,
  
  CellTypist_confidence = conf_i,
  
  stringsAsFactors = FALSE
)


# Store batch predictions.

prediction_list[[i]] <- batch_df


# Save individual batch results.

write.csv(
  
  batch_df,
  
  out_dir(
    "annotation",
    paste0(
      "celltypist_batch_",
      i,
      ".csv"
    )
  ),
  
  row.names = FALSE
)


# Remove temporary R objects to reduce memory usage.

rm(
  mat_i,
  adata_i,
  labels_i,
  conf_i,
  batch_df
)

gc()


# Remove temporary Python objects and collect garbage.

py_run_string(
  "
del pred_i, labels_i, conf_i, adata_i

import gc
gc.collect()
"
)
}


############################################################
# 10. Combine Batch-Wise Predictions
############################################################

# Combine all batch-level prediction tables.

predictions <- do.call(
  rbind,
  prediction_list
)


# Check for duplicated cell identifiers.

if (anyDuplicated(predictions$cell)) {
  
  stop(
    "Duplicate cell IDs detected in CellTypist output."
  )
}


# Match CellTypist predictions to the original Seurat
# object cell order.

idx <- match(
  colnames(obj),
  predictions$cell
)


# Ensure that every cell has a corresponding prediction.

if (anyNA(idx)) {
  
  stop(
    "Some immune cells are missing CellTypist predictions."
  )
}


############################################################
# 11. Add CellTypist Results to Seurat Metadata
############################################################

# Add predicted cell-type labels.

obj$CellTypist_label <- predictions$CellTypist_label[idx]


# Add prediction confidence scores.

obj$CellTypist_confidence <-
  predictions$CellTypist_confidence[idx]


############################################################
# 12. Export CellTypist Annotation Results
############################################################

# Save the complete cell-level prediction table.

write.csv(
  
  predictions,
  
  out_dir(
    "annotation",
    "05_celltypist_all_predictions.csv"
  ),
  
  row.names = FALSE
)


# Summarize the number of cells assigned to each
# CellTypist-predicted cell type.

celltypist_summary <- as.data.frame(
  table(obj$CellTypist_label)
)

colnames(celltypist_summary) <- c(
  "CellTypist_label",
  "Cells"
)


# Save CellTypist label counts.

write.csv(
  
  celltypist_summary,
  
  out_dir(
    "annotation",
    "06_celltypist_label_counts.csv"
  ),
  
  row.names = FALSE
)


