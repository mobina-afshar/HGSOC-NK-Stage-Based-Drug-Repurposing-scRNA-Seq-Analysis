
############################################################
# GSE184880 - HGSOC scRNA-seq Analysis
# Script 03: Preprocessing and Global Clustering
#
# Purpose:
# Normalize the filtered expression matrix, calculate cell-cycle
# scores, identify highly variable genes, perform scaling and PCA,
# and generate global cell clusters and UMAP visualization.
#
# Input:
# - config.yaml
# - results/rds/02_HGSOC_QC.rds
#
# Output:
# - Cell-cycle summary
# - Highly variable gene list
# - PCA elbow plot
# - Global cluster size summary
# - Global UMAP visualization
# - results/rds/03_HGSOC_global_clustered.rds
# - logs/03_preprocessing_clustering_sessionInfo.txt
#
# IMPORTANT:
# - Cell-cycle scores are retained as metadata.
# - Cell-cycle regression is not performed.
# - Global clustering parameters are defined in config.yaml.
# - The RNA assay is used for normalization and downstream analysis.
############################################################


############################################################
# 1. Load Project Configuration
############################################################

# Ensure that the script is launched from the repository root.

if (!file.exists("config.yaml")) {
  stop(
    "config.yaml was not found. ",
    "Run this script from the project root."
  )
}

# Check and load the YAML package.

if (!requireNamespace("yaml", quietly = TRUE)) {
  stop(
    "Package 'yaml' is required. ",
    "Install it using install.packages('yaml')."
  )
}

# Read project configuration.

cfg <- yaml::read_yaml("config.yaml")

# Define project directories.

PROJECT_ROOT <- normalizePath(
  getwd(),
  winslash = "/",
  mustWork = TRUE
)

RESULTS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$results
)

LOGS_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$logs
)

RAW_DIR <- file.path(
  PROJECT_ROOT,
  cfg$paths$raw_data
)

RDS_DIR <- file.path(
  RESULTS_DIR,
  "rds"
)

# Create required output directories.

dir.create(
  RESULTS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  LOGS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  RDS_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)

# Set project-wide random seed.

set.seed(cfg$project$seed)


############################################################
# 2. Define Shared Helper Functions
############################################################

# Generate output file paths and create parent directories.

out_dir <- function(...) {
  
  path <- file.path(
    RESULTS_DIR,
    ...
  )
  
  dir.create(
    dirname(path),
    recursive = TRUE,
    showWarnings = FALSE
  )
  
  return(path)
}


# Check whether required R packages are installed.

require_pkgs <- function(pkgs) {
  
  missing <- pkgs[
    !vapply(
      pkgs,
      requireNamespace,
      logical(1),
      quietly = TRUE
    )
  ]
  
  if (length(missing) > 0) {
    
    stop(
      "Install missing packages before continuing: ",
      paste(missing, collapse = ", ")
    )
  }
}


# Save R session information for reproducibility.

save_session <- function(tag) {
  
  capture.output(
    sessionInfo(),
    file = file.path(
      LOGS_DIR,
      paste0(tag, "_sessionInfo.txt")
    )
  )
}


############################################################
# 3. Load Required Packages
############################################################

require_pkgs(
  c(
    "Seurat",
    "ggplot2"
  )
)

library(Seurat)
library(ggplot2)


############################################################
# 4. Load Filtered Seurat Object
############################################################

# Load the quality-controlled Seurat object generated by Script 02.

input_rds <- out_dir(
  "rds",
  "02_HGSOC_QC.rds"
)

if (!file.exists(input_rds)) {
  
  stop(
    "Run Script 02 first. Missing input file: ",
    input_rds
  )
}

HGSOC_QC <- readRDS(input_rds)


# Set the RNA assay as the default assay.

DefaultAssay(HGSOC_QC) <- "RNA"


############################################################
# 5. Normalize Gene Expression
############################################################

# Normalize RNA counts using LogNormalize.
#
# Scale factor: 10,000
#
# Normalized expression values are stored in the RNA assay.

HGSOC_QC <- NormalizeData(
  
  HGSOC_QC,
  
  normalization.method = "LogNormalize",
  
  scale.factor = 10000,
  
  verbose = FALSE
)


############################################################
# 6. Calculate Cell-Cycle Scores
############################################################

# Assign cell-cycle scores using the updated 2019 Seurat
# S-phase and G2M-phase gene lists.
#
# Cell-cycle information is added to metadata.
# The original cell identity is not changed.

HGSOC_QC <- CellCycleScoring(
  
  HGSOC_QC,
  
  s.features = Seurat::cc.genes.updated.2019$s.genes,
  
  g2m.features = Seurat::cc.genes.updated.2019$g2m.genes,
  
  set.ident = FALSE
)


# Summarize the number of cells assigned to each cell-cycle phase.

cell_cycle_summary <- as.data.frame(
  table(HGSOC_QC$Phase)
)

colnames(cell_cycle_summary) <- c(
  "Phase",
  "Cells"
)


# Save cell-cycle summary.

write.csv(
  
  cell_cycle_summary,
  
  out_dir(
    "preprocessing",
    "01_cell_cycle_summary.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 7. Identify Highly Variable Genes
############################################################

# Identify highly variable genes using the variance-stabilizing
# transformation (VST) method.
#
# The number of selected genes is defined in config.yaml.

HGSOC_QC <- FindVariableFeatures(
  
  HGSOC_QC,
  
  selection.method = "vst",
  
  nfeatures = cfg$seurat$n_hvg,
  
  verbose = FALSE
)


# Extract and rank highly variable genes.

hvg_list <- data.frame(
  
  rank = seq_along(
    VariableFeatures(HGSOC_QC)
  ),
  
  gene = VariableFeatures(HGSOC_QC),
  
  stringsAsFactors = FALSE
)


# Save highly variable gene list.

write.csv(
  
  hvg_list,
  
  out_dir(
    "preprocessing",
    "02_highly_variable_genes.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 8. Scale Gene Expression
############################################################

# Scale the expression values of highly variable genes.
#
# Cell-cycle scores are retained as metadata and are not
# regressed out, matching the established analysis workflow.

HGSOC_QC <- ScaleData(
  
  HGSOC_QC,
  
  features = VariableFeatures(HGSOC_QC),
  
  verbose = FALSE
)


############################################################
# 9. Perform Principal Component Analysis
############################################################

# Perform PCA using highly variable genes.
#
# A total of 50 principal components are calculated.

HGSOC_QC <- RunPCA(
  
  HGSOC_QC,
  
  features = VariableFeatures(HGSOC_QC),
  
  npcs = 50,
  
  seed.use = cfg$project$seed,
  
  verbose = FALSE
)


# Generate an elbow plot to inspect the variance explained
# across principal components.

p_elbow <- ElbowPlot(
  
  HGSOC_QC,
  
  ndims = 50
)


# Save PCA elbow plot.

ggsave(
  
  out_dir(
    "preprocessing",
    "03_pca_elbow.png"
  ),
  
  p_elbow,
  
  width = 8,
  
  height = 6,
  
  dpi = 300
)


############################################################
# 10. Identify Global Cell Neighbors
############################################################

# Construct the shared nearest-neighbor graph using the
# configured number of principal components.

HGSOC_QC <- FindNeighbors(
  
  HGSOC_QC,
  
  reduction = "pca",
  
  dims = seq_len(
    cfg$seurat$n_pcs_global
  ),
  
  verbose = FALSE
)


############################################################
# 11. Perform Global Clustering
############################################################

# Identify cell clusters using the configured global resolution.
#
# Algorithm 1 corresponds to the original Louvain clustering
# algorithm used in this workflow.

HGSOC_QC <- FindClusters(
  
  HGSOC_QC,
  
  resolution = cfg$seurat$global_resolution,
  
  algorithm = 1,
  
  random.seed = cfg$project$seed,
  
  verbose = FALSE
)


############################################################
# 12. Generate Global UMAP Embedding
############################################################

# Calculate the two-dimensional UMAP representation using
# the same principal components used for neighbor detection.

HGSOC_QC <- RunUMAP(
  
  HGSOC_QC,
  
  reduction = "pca",
  
  dims = seq_len(
    cfg$seurat$n_pcs_global
  ),
  
  seed.use = cfg$project$seed,
  
  verbose = FALSE
)


############################################################
# 13. Summarize Global Cluster Sizes
############################################################

# Calculate the number of cells assigned to each global cluster.

cluster_summary <- as.data.frame(
  table(HGSOC_QC$seurat_clusters)
)

colnames(cluster_summary) <- c(
  "Cluster",
  "Cells"
)


# Save global cluster size summary.

write.csv(
  
  cluster_summary,
  
  out_dir(
    "preprocessing",
    "04_global_cluster_sizes.csv"
  ),
  
  row.names = FALSE
)


############################################################
# 14. Visualize Global Clustering Results
############################################################

# Generate a UMAP plot colored by global Seurat cluster identity.

p_umap <- DimPlot(
  
  HGSOC_QC,
  
  reduction = "umap",
  
  group.by = "seurat_clusters",
  
  label = TRUE,
  
  repel = TRUE
) +
  
  theme_classic()


# Save global UMAP visualization.

ggsave(
  
  out_dir(
    "preprocessing",
    "05_global_umap_clusters.png"
  ),
  
  p_umap,
  
  width = 10,
  
  height = 8,
  
  dpi = 300
)


############################################################
# 15. Save Global Clustered Seurat Object
############################################################

# Save the processed Seurat object containing:
# - Normalized expression
# - Cell-cycle scores
# - Highly variable genes
# - Scaled expression
# - PCA embeddings
# - Global cluster identities
# - UMAP coordinates

saveRDS(
  
  HGSOC_QC,
  
  out_dir(
    "rds",
    "03_HGSOC_global_clustered.rds"
  )
)


############################################################
# 16. Report Preprocessing and Clustering Results
############################################################

